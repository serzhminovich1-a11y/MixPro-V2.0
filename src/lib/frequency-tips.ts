/** Pick the tip whose representative frequency is nearest to `hz`. */
export function tipFor(hz: number): FrequencyTip {
  let best = FREQUENCY_TIPS[0];
  let bestDist = Infinity;
  for (const t of FREQUENCY_TIPS) {
    // distance in log space (octaves)
    const d = Math.abs(Math.log2(t.hz / hz));
    if (d < bestDist) { bestDist = d; best = t; }
  }
  return best;
}
